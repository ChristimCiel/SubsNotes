  const normalizeLanguage = value => ['zh','zh-TW','zh-Hant','zh-Hant-TW'].includes(value) ? 'zh-TW' : 'en';
  const locale = language => normalizeLanguage(language)==='zh-TW'?'zh-TW':'en-US';
  const t = (key, language='en', params={}) => String(messages[normalizeLanguage(language)][key] ?? messages.en[key] ?? key).replace(/\{(\w+)\}/g,(_,name)=>Object.hasOwn(params,name)?String(params[name]):'{'+name+'}');
  const month = (value,language='en') => typeof value==='string'&&/^20\d{2}-(?:0[1-9]|1[0-2])$/.test(value)?new Intl.DateTimeFormat(locale(language),{year:'numeric',month:'long',timeZone:'UTC'}).format(new Date(value+'-01T00:00:00Z')):t('unknown',language);
  const date = (value,language='en') => {
    if(typeof value==='string'&&/^20\d{2}-\d{2}$/.test(value))return month(value,language);
    if(!value||!Number.isFinite(Date.parse(value)))return t('unknown',language);
    const dateOnly=/^\d{4}-\d{2}-\d{2}$/.test(value);
    if(dateOnly&&new Date(value).toISOString().slice(0,10)!==value)return t('unknown',language);
    return new Intl.DateTimeFormat(locale(language),{year:'numeric',month:'short',day:'numeric',...(dateOnly?{timeZone:'UTC'}:{})}).format(new Date(value));
  };
  const money = (amount,language='en') => {
    if(!amount)return t('noAmount',language);
    if(!amount.currency||!Intl.supportedValuesOf('currency').includes(amount.currency))return t('currencyUnknown',language);
    if(!Number.isSafeInteger(amount.minor))return t('noAmount',language);
    const format=new Intl.NumberFormat(locale(language),{style:'currency',currency:amount.currency,currencyDisplay:'code'});
    return format.format(amount.minor/10**format.resolvedOptions().maximumFractionDigits);
  };
  const error = (value,language='en') => {
    if(messages.en['error_'+value?.code])return t('error_'+value.code,language);
    const message=typeof value==='string'?value:value?.message;
    for(const [key,text]of Object.entries(messages.en))if(text===message||messages['zh-TW'][key]===message)return t(key,language);
    if(/another tab|Records changed|conditional commit/i.test(message||''))return t('error_confirmation_stale',language);
    return t('error_generic',language);
  };
  const warning = (text,language='en') => {const key=['warningAdjustment','warningInvoice','warningLaterPlan','warningFailure','warningRenewal'].find(key=>messages.en[key]===text);return t(key||'warningGeneric',language);};
  return {normalizeLanguage,locale,t,date,month,money,error,warning,languages:['en','zh-TW'],keys:()=>Object.keys(messages.en),messages};
